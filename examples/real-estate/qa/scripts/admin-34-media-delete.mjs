import { launch, ctx, shot, BASE, logErrors, toasts } from './admin-lib.mjs';
const b = await launch(); const c = await ctx(b); const p = await c.newPage(); logErrors(p);
p.on('dialog', d => d.accept());
await p.goto(BASE + '/admin/media', { waitUntil: 'networkidle' });
await p.getByText('qa-test-upload', { exact: true }).first().click(); await p.waitForTimeout(800);
await shot(p, '92-media-details');
const btns = await p.$$eval('button', e => e.map(x => (x.getAttribute('aria-label') || '') + '|' + x.innerText.trim()).filter(x => /trash|delete/i.test(x))); console.log(btns);
await p.getByRole('button', { name: /move to trash/i }).first().click(); await p.waitForTimeout(600);
const confirm = p.getByRole('alertdialog').getByRole('button', { name: /trash|continue|delete/i }); if (await confirm.count()) await confirm.first().click();
console.log('trash', await toasts(p));
await p.getByRole('button', { name: 'Trash', exact: true }).click().catch(() => p.getByText('Trash', { exact: true }).click()); await p.waitForTimeout(1000);
await p.getByText('qa-test-upload', { exact: true }).first().click(); await p.waitForTimeout(800);
console.log(await p.$$eval('button', e => e.map(x => x.innerText.trim()).filter(x => /delete|restore/i.test(x))));
await p.getByRole('button', { name: /delete for good/i }).first().click(); await p.waitForTimeout(600);
const c2 = p.getByRole('alertdialog').getByRole('button', { name: /delete|continue/i }); if (await c2.count()) await c2.last().click();
console.log('delete', await toasts(p)); await shot(p, '93-media-deleted');
await b.close();
