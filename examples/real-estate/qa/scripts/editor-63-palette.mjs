import { launch, session, shot, BASE } from './editor-lib.mjs';
const b = await launch(); const { c, p } = await session(b, 'budi');
await p.goto(BASE + '/admin', { waitUntil: 'networkidle' });
await p.keyboard.press('Control+k'); await p.waitForTimeout(500);
await shot(p, '106-palette-open');
console.log('open', (await p.locator('[role=dialog]').innerText().catch(() => 'none')).slice(0, 500));
const t0 = Date.now();
await p.keyboard.type('menteng', { delay: 40 }); await p.waitForTimeout(900);
console.log('results', await p.getByRole('option').allInnerTexts(), Date.now() - t0, 'ms');
await shot(p, '107-palette-search');
await p.keyboard.press('Enter'); await p.waitForLoadState('networkidle'); await p.waitForTimeout(400);
console.log('went to', p.url());
// search by id and by Indonesian title
await p.keyboard.press('Control+k'); await p.waitForTimeout(400);
await p.keyboard.type('rumah taman'); await p.waitForTimeout(900);
console.log('id-title results', await p.getByRole('option').allInnerTexts());
await p.keyboard.press('Escape');
await p.keyboard.press('Control+k'); await p.waitForTimeout(400);
await p.keyboard.type('new property'); await p.waitForTimeout(900);
console.log('action results', await p.getByRole('option').allInnerTexts());
await p.keyboard.press('Escape');
await p.keyboard.press('Control+k'); await p.waitForTimeout(400);
await p.keyboard.type('#12'); await p.waitForTimeout(900);
console.log('#12 results', await p.getByRole('option').allInnerTexts());
await b.close();
