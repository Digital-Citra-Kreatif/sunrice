import { launch, session, shot, BASE } from './editor-lib.mjs';
const b = await launch(); const { c, p } = await session(b, 'budi');
await p.goto(BASE + '/admin/cms/collections/properties/entries/create', { waitUntil: 'networkidle' });
await p.click('#data-agent'); await p.waitForTimeout(800);
console.log('agent opts on focus', await p.getByRole('option').allInnerTexts());
await p.fill('#data-agent', 'Raf'); await p.waitForTimeout(900);
console.log('agent opts', await p.getByRole('option').allInnerTexts());
await shot(p, '14-entry-picker-search');
await p.getByRole('option').first().click(); await p.waitForTimeout(300);
await shot(p, '15-entry-picker-picked');
await p.click('#data-location'); await p.waitForTimeout(300);
console.log('location opts', await p.getByRole('option').allInnerTexts());
await shot(p, '16-location-select');
await p.keyboard.press('Escape');
await p.click('#data-property_status'); await p.waitForTimeout(300);
console.log('status opts', await p.getByRole('option').allInnerTexts());
await p.keyboard.press('Escape');
await p.click('#data-price_suffix'); await p.waitForTimeout(300);
console.log('suffix', await p.getByRole('option').allInnerTexts());
await b.close();
