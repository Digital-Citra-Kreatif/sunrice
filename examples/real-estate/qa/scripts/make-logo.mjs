// Builds public/images/lumina-logo.svg (and the inline partial and favicon) with the wordmark
// outlined from the site's own fonts, so the logo never depends on fonts being loaded.
// Run: NODE_PATH=<dir with opentype.js> node qa/scripts/make-logo.mjs
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
const require = createRequire(import.meta.url + '/../../');
const opentype = require(process.env.NODE_PATH + '/opentype.js');
const root = new URL('../../', import.meta.url).pathname;
import { readFileSync } from 'node:fs';
const font = (p) => { const b = readFileSync(root + 'node_modules/@fontsource/' + p); return opentype.parse(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength)); };
const serif = font('cormorant-garamond/files/cormorant-garamond-latin-600-normal.woff');
const sans = font('manrope/files/manrope-latin-600-normal.woff');

function text(f, str, x, y, size, tracking) {
    let d = '';
    let cursor = x;
    for (const ch of str) {
        const glyph = f.charToGlyph(ch);
        d += glyph.getPath(cursor, y, size).toPathData(2);
        cursor += (glyph.advanceWidth / f.unitsPerEm) * size + tracking;
    }
    return { d, width: cursor - tracking - x };
}

const word = text(serif, 'LUMINA', 58, 36, 34, 3.2);
const sub = text(sans, 'ESTATES', 59, 51, 8.6, 4.9);
const width = Math.ceil(Math.max(58 + word.width, 59 + sub.width) + 2);

const mark = `
    <g class="logo-mark" fill="none" stroke-linecap="round" stroke-width="2.4">
      <path class="logo-mark-stroke" stroke="#0f403d" d="M6 50V22a17 17 0 0 1 34 0v28"/>
      <path class="logo-mark-stroke" stroke="#0f403d" d="M1 50.5h44"/>
      <path class="logo-mark-fill" fill="#0f403d" stroke="none" d="M14 50a9 9 0 0 1 18 0z"/>
      <path class="logo-mark-stroke" stroke="#0f403d" stroke-width="1.8" d="M23 36.5v-4M15.2 39.6l-2.6-2.6M30.8 39.6l2.6-2.6"/>
    </g>`;

const svg = (title) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} 56" role="img" aria-labelledby="lumina-logo-title">
  <title id="lumina-logo-title">${title}</title>${mark}
    <path class="logo-word" fill="#1f1b16" d="${word.d}"/>
    <path class="logo-word" fill="#1f1b16" d="${sub.d}"/>
</svg>
`;
writeFileSync(root + 'public/images/lumina-logo.svg', svg('Lumina Estates'));

// The inline version for the header: colours follow currentColor (so it turns white over a hero).
const inline = svg('{{ $label }}')
    .replace('role="img" aria-labelledby="lumina-logo-title"', 'role="img" aria-labelledby="{{ $id }}" class="{{ $class }}"')
    .replace('id="lumina-logo-title"', 'id="{{ $id }}"')
    .replaceAll('stroke="#0f403d"', 'stroke="currentColor"')
    .replaceAll('fill="#0f403d"', 'fill="currentColor"')
    .replaceAll('fill="#1f1b16"', 'fill="currentColor"');
writeFileSync(root + 'resources/views/cms/partials/logo.blade.php',
    `{{-- Generated by qa/scripts/make-logo.mjs: the logo inline, in currentColor. @include('cms.partials.logo', ['id' => 'logo-header', 'label' => …, 'class' => …]) --}}\n` + inline);

// Favicon: the mark alone on ivory, rounded.
writeFileSync(root + 'public/favicon.svg', `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">
  <rect width="64" height="64" rx="14" fill="#0f403d"/>
  <g transform="translate(9 6)" fill="none" stroke="#faf7f2" stroke-linecap="round" stroke-width="3">
    <path d="M6 50V22a17 17 0 0 1 34 0v28"/>
    <path d="M1 50.5h44"/>
    <path fill="#faf7f2" stroke="none" d="M14 50a9 9 0 0 1 18 0z"/>
    <path stroke-width="2.4" d="M23 36.5v-4M15.2 39.6l-2.6-2.6M30.8 39.6l2.6-2.6"/>
  </g>
</svg>
`);
