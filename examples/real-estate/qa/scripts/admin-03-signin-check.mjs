import { launch, ctx, shot, BASE, logErrors } from './admin-lib.mjs';
const b = await launch();
const c2 = await ctx(b, { state: false }); const p2 = await c2.newPage(); logErrors(p2);
await p2.goto(BASE + '/admin/login', { waitUntil: 'networkidle' });
await shot(p2, '08-signin-branded');
console.log(await p2.title());
console.log(await p2.$$eval('link[rel*=icon]', l => l.map(x => x.outerHTML)));
await p2.setViewportSize({ width: 390, height: 844 }); await shot(p2, '09-signin-mobile');
const r = await p2.request.get(BASE + '/favicon.ico'); console.log('favicon.ico', r.status(), r.headers()['content-type']);
await b.close();
